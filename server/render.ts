import type { NotebookEntry } from '../shared/entry.ts'

export const slugify = (title: string) =>
  title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 60).replace(/-+$/, '') || 'entry'

const list = (xs: string[]) => xs.map((x) => `- ${x}`).join('\n')

/**
 * The archived Markdown (design.md §6.5). Pure: same entry → same bytes, so mirror diffs stay clean.
 * Images point at assets/<date>/<id>.jpg relative to entries/, matching the zip / mirror layout.
 */
export function renderMarkdown(e: NotebookEntry, meta: { submitted_by?: string | null; approved_by?: string | null; approved_at?: string | null } = {}) {
  const time = [e.start_time, e.end_time].filter(Boolean).join('–')
  const out = [
    '<!-- Generated by Glaucus. Do not edit by hand: changes go through the web app. -->',
    `# ${e.title}`,
    '',
    [
      `**Date:** ${e.date}${time ? ` · ${time}` : ''}`,
      `**Attendees:** ${e.attendees.join(', ') || '—'}`,
      ...(meta.approved_by ? [`**Submitted by:** ${meta.submitted_by ?? '—'} · **Approved by:** ${meta.approved_by} (${meta.approved_at})`] : []),
    ].join('  \n'),
  ]
  if (e.goals.length) out.push('', '## Goals', '', list(e.goals))
  for (const s of e.sections) {
    out.push('', `## ${s.subsystem}`, '', s.work_done)
    if (s.problems.length) out.push('', '### Problems', '', list(s.problems))
    if (s.decisions.length) {
      out.push('', '### Decisions')
      for (const d of s.decisions) {
        out.push('', `**${d.decision}**`, '')
        if (d.alternatives_considered.length) out.push(`- Alternatives considered: ${d.alternatives_considered.join('; ')}`)
        out.push(`- Rationale: ${d.rationale}`)
      }
    }
    if (s.test_results) out.push('', '### Test results', '', s.test_results)
    for (const im of s.images) out.push('', `![${im.caption}](../assets/${e.date}/${im.attachment_id}.jpg)`, im.caption ? `*${im.caption}*` : '')
  }
  if (e.next_steps.length) out.push('', '## Next steps', '', list(e.next_steps))
  return out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n'
}
